-- 0001_initial_schema.sql
-- Matchup Library, v1.
--
-- Capture and documentation come first. Nothing is rated: there is no
-- prevalence or strength score. What a civ does is documented with tags that
-- carry timings, tells and notes, and with references: games and guides.
--
-- The shape
--   Things you define: civs, maps (under map types, with map features),
--   elements, and plays (table: strategies), which are ordered combinations
--   of elements.
--   Records that connect them:
--     tags         a civ does an element or a whole play, optionally in an age
--                  and a place
--     comes up on  maps where an element or play matters, for any civ
--     games        any game, yours or anyone's, with what each side did in order
--     links        footage or pages for a game, or a standalone guide, with
--                  timestamped moments (link_marks)
--     answers      your responses to an element or a play (not in the v1 app yet)
-- Gaps and matchups are never stored. The v1 app works them out in the page.
--
-- Plays are combinations of elements
--   An element is one building block: a barracks opening, a tower rush, a
--   second town centre, men-at-arms spam.
--   A play is an ordered list of elements. Elements that share a step happen
--   together; a higher step comes later. Step numbers only set the order.
--   A play lists only what departs from standard play.
--
-- Ages are not gated unless certain
--   Each element has four flags for the ages it can happen in, all on by
--   default. The age something actually happened in is recorded where it
--   happened: a play step, a game play on a single element, or a moment.
--   Tags and element answers can carry an optional age; empty means any age.
--   A tag with an age only counts for a play step of the same age.
--
-- Places
--   Tags and answers apply to one place at a time: anywhere (all empty), a
--   map type, a map feature, or one specific map. Two places means two rows.
--
-- Ids
--   Definitions (civs, maps, elements, plays and so on) use stable text slugs.
--   Records the app creates (tags, games, plays in games, links, moments,
--   answers) use text ids generated by the app, so the page can create and
--   link records before it saves them.
--
-- Conventions
--   Civ ids use aoe4world's civ slugs so rows can be matched to aoe4-analyzer
--   data at the application layer (D1 cannot join across databases).
--   Retire, never delete: definitions and tags have is_active. 0 retires a row
--   and 1 restores it. Retired rows stay attached to whatever used them.
--   Duplicate plays are merged: the app moves every reference to the
--   surviving play, then retires the duplicate with merged_into_id set.
--   Every change the app makes is recorded in change_log, in the same D1
--   batch, so mistakes can be undone without the D1 console.
--   No BEGIN/COMMIT: D1 does not accept explicit transactions in SQL files.
--   No UNION with more than two terms: D1 limits compound SELECTs.
--   This file holds structure only. Data is loaded separately.


-- ===========================================================================
-- Reference tables
-- ===========================================================================
CREATE TABLE civs (
  id             TEXT PRIMARY KEY,              -- aoe4world civ slug
  name           TEXT NOT NULL,
  short_name     TEXT,                          -- for tight layouts, e.g. HRE, OotD
  flag_slug      TEXT,                          -- flag image at /flags/{flag_slug}.png
  parent_civ_id  TEXT REFERENCES civs (id),     -- set for variant civs
  is_active      INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at     TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE map_types (
  id           TEXT PRIMARY KEY,                -- open, closed, hybrid, naval
  name         TEXT NOT NULL,
  description  TEXT,
  sort_order   INTEGER NOT NULL DEFAULT 0,
  is_active    INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at   TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE maps (
  id              TEXT PRIMARY KEY,             -- our slug, e.g. dry-arabia
  name            TEXT NOT NULL,
  aoe4world_name  TEXT UNIQUE,                  -- map name exactly as aoe4world reports it
  map_type_id     TEXT NOT NULL REFERENCES map_types (id),
  in_pool         INTEGER NOT NULL DEFAULT 1 CHECK (in_pool IN (0, 1)),    -- in the current ranked rotation
  is_active       INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),  -- 0 = retired
  notes           TEXT,
  created_at      TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_maps_map_type ON maps (map_type_id);

-- Characteristics that change how plays and answers work, e.g. exposed close
-- gold, easy to wall. A feature on a map means "usually has this".
CREATE TABLE map_features (
  id           TEXT PRIMARY KEY,
  name         TEXT NOT NULL,
  description  TEXT,
  sort_order   INTEGER NOT NULL DEFAULT 0,
  is_active    INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at   TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE map_has_feature (
  map_id      TEXT NOT NULL REFERENCES maps (id) ON DELETE CASCADE,
  feature_id  TEXT NOT NULL REFERENCES map_features (id) ON DELETE CASCADE,
  notes       TEXT,
  PRIMARY KEY (map_id, feature_id)
);
CREATE INDEX ix_map_has_feature_feature ON map_has_feature (feature_id);


-- ===========================================================================
-- Elements and plays
-- ===========================================================================
CREATE TABLE element_kinds (
  id           TEXT PRIMARY KEY,                -- e.g. production, army, structure, age_up
  name         TEXT NOT NULL,
  description  TEXT,
  sort_order   INTEGER NOT NULL DEFAULT 0,
  is_active    INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1))
);

-- One building block of a play. Split an element when the answer to it
-- differs, not when the build differs.
CREATE TABLE elements (
  id            TEXT PRIMARY KEY,
  name          TEXT NOT NULL,
  kind_id       TEXT NOT NULL REFERENCES element_kinds (id),
  age_dark      INTEGER NOT NULL DEFAULT 1 CHECK (age_dark IN (0, 1)),
  age_feudal    INTEGER NOT NULL DEFAULT 1 CHECK (age_feudal IN (0, 1)),
  age_castle    INTEGER NOT NULL DEFAULT 1 CHECK (age_castle IN (0, 1)),
  age_imperial  INTEGER NOT NULL DEFAULT 1 CHECK (age_imperial IN (0, 1)),
  tells         TEXT,                           -- what anyone doing it looks like when scouted
  description   TEXT,
  where_note    TEXT,                           -- why it comes up on the places in comes_up_on
  is_active     INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  merged_into_id TEXT REFERENCES elements (id),
  created_at    TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (age_dark + age_feudal + age_castle + age_imperial >= 1),
  CHECK (merged_into_id IS NULL OR (merged_into_id <> id AND is_active = 0))
);
CREATE INDEX ix_elements_kind ON elements (kind_id);

-- A play: a named combination of elements.
CREATE TABLE strategies (
  id              TEXT PRIMARY KEY,
  name            TEXT NOT NULL,
  description     TEXT,
  notes           TEXT,
  where_note      TEXT,
  is_active       INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  merged_into_id  TEXT REFERENCES strategies (id),
  created_at      TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (merged_into_id IS NULL OR (merged_into_id <> id AND is_active = 0))
);

-- The elements of a play, in order. Same step_no = at the same time.
CREATE TABLE strategy_elements (
  strategy_id  TEXT NOT NULL REFERENCES strategies (id) ON DELETE CASCADE,
  step_no      INTEGER NOT NULL CHECK (step_no >= 1),
  element_id   TEXT NOT NULL REFERENCES elements (id),
  age          TEXT CHECK (age IS NULL OR age IN ('dark', 'feudal', 'castle', 'imperial')),
  notes        TEXT,
  PRIMARY KEY (strategy_id, step_no, element_id)
);
CREATE INDEX ix_strategy_elements_element ON strategy_elements (element_id);

-- Maps where an element or a play comes up, for any civ: a map type, a
-- feature or one map per row. The reason is the element's or play's where_note.
CREATE TABLE comes_up_on (
  id           INTEGER PRIMARY KEY,
  element_id   TEXT REFERENCES elements (id) ON DELETE CASCADE,
  strategy_id  TEXT REFERENCES strategies (id) ON DELETE CASCADE,
  map_type_id  TEXT REFERENCES map_types (id),
  feature_id   TEXT REFERENCES map_features (id),
  map_id       TEXT REFERENCES maps (id),
  CHECK ((element_id IS NULL) <> (strategy_id IS NULL)),
  CHECK ((map_type_id IS NOT NULL) + (feature_id IS NOT NULL) + (map_id IS NOT NULL) = 1)
);
CREATE INDEX ix_comes_up_on_element ON comes_up_on (element_id) WHERE element_id IS NOT NULL;
CREATE INDEX ix_comes_up_on_strategy ON comes_up_on (strategy_id) WHERE strategy_id IS NOT NULL;


-- ===========================================================================
-- Tags: what a civ does
-- ===========================================================================

-- "This civ does this element", or "this civ runs this whole play", with
-- timings, civ-specific tells and notes. Optionally one age (elements only)
-- and one place. One tag per civ, target, age and place, retired or not; the
-- expression index enforces that, because SQLite treats NULLs as distinct.
-- A tag on a whole play also counts for each of the play's elements.
CREATE TABLE civ_element_tags (
  id           TEXT PRIMARY KEY,
  civ_id       TEXT NOT NULL REFERENCES civs (id),
  element_id   TEXT REFERENCES elements (id),
  strategy_id  TEXT REFERENCES strategies (id),
  age          TEXT CHECK (age IS NULL OR age IN ('dark', 'feudal', 'castle', 'imperial')),
  map_type_id  TEXT REFERENCES map_types (id),
  feature_id   TEXT REFERENCES map_features (id),
  map_id       TEXT REFERENCES maps (id),
  timing_note  TEXT,
  tells        TEXT,
  notes        TEXT,
  last_confirmed_on  TEXT,                      -- YYYY-MM-DD
  is_active    INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at   TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((element_id IS NULL) <> (strategy_id IS NULL)),
  CHECK (age IS NULL OR element_id IS NOT NULL),
  CHECK ((map_type_id IS NOT NULL) + (feature_id IS NOT NULL) + (map_id IS NOT NULL) <= 1)
);
CREATE UNIQUE INDEX ux_civ_element_tags
  ON civ_element_tags (civ_id, COALESCE(element_id, ''), COALESCE(strategy_id, ''), COALESCE(age, ''),
                       COALESCE(map_type_id, ''), COALESCE(feature_id, ''), COALESCE(map_id, ''));
CREATE INDEX ix_civ_element_tags_element ON civ_element_tags (element_id) WHERE element_id IS NOT NULL;
CREATE INDEX ix_civ_element_tags_strategy ON civ_element_tags (strategy_id) WHERE strategy_id IS NOT NULL;


-- ===========================================================================
-- Answers (kept for the next version; the v1 app does not edit them)
-- ===========================================================================
CREATE TABLE responses (
  id               TEXT PRIMARY KEY,
  strategy_id      TEXT REFERENCES strategies (id),
  element_id       TEXT REFERENCES elements (id),
  age              TEXT CHECK (age IS NULL OR age IN ('dark', 'feudal', 'castle', 'imperial')),
  my_civ_id        TEXT REFERENCES civs (id),
  opponent_civ_id  TEXT REFERENCES civs (id),
  map_type_id      TEXT REFERENCES map_types (id),
  feature_id       TEXT REFERENCES map_features (id),
  map_id           TEXT REFERENCES maps (id),
  title            TEXT NOT NULL,
  plan             TEXT,
  status           TEXT NOT NULL DEFAULT 'idea'
                   CHECK (status IN ('idea', 'studying', 'practiced', 'proven')),
  notes            TEXT,
  last_confirmed_on  TEXT,
  is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at       TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((strategy_id IS NULL) <> (element_id IS NULL)),
  CHECK (age IS NULL OR element_id IS NOT NULL),
  CHECK ((map_type_id IS NOT NULL) + (feature_id IS NOT NULL) + (map_id IS NOT NULL) <= 1)
);
CREATE INDEX ix_responses_strategy ON responses (strategy_id) WHERE strategy_id IS NOT NULL;
CREATE INDEX ix_responses_element ON responses (element_id) WHERE element_id IS NOT NULL;

CREATE TABLE response_steps (
  response_id          TEXT NOT NULL REFERENCES responses (id) ON DELETE CASCADE,
  step_no              INTEGER NOT NULL CHECK (step_no >= 1),
  element_response_id  TEXT REFERENCES responses (id),
  note                 TEXT,
  PRIMARY KEY (response_id, step_no),
  CHECK (element_response_id IS NOT NULL OR note IS NOT NULL),
  CHECK (element_response_id IS NULL OR element_response_id <> response_id)
);
CREATE INDEX ix_response_steps_element_response ON response_steps (element_response_id);


-- ===========================================================================
-- References: games, links and moments
-- ===========================================================================

-- Any game, yours or anyone's. The "player" is the side you follow: you in
-- your own games. result is from the player's side.
CREATE TABLE games (
  id                 TEXT PRIMARY KEY,
  is_mine            INTEGER NOT NULL DEFAULT 0 CHECK (is_mine IN (0, 1)),
  title              TEXT,                              -- optional; the app shows civs and map otherwise
  played_on          TEXT,                              -- YYYY-MM-DD, if known
  player_name        TEXT,
  player_civ_id      TEXT REFERENCES civs (id),
  opponent_name      TEXT,
  opponent_civ_id    TEXT REFERENCES civs (id),
  map_id             TEXT REFERENCES maps (id),
  result             TEXT CHECK (result IN ('win', 'loss')),
  aoe4world_game_id  INTEGER,                           -- bridge to aoe4-analyzer
  notes              TEXT,
  created_at         TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_games_player_civ ON games (player_civ_id);
CREATE INDEX ix_games_opponent_civ ON games (opponent_civ_id);
CREATE INDEX ix_games_map ON games (map_id);
CREATE INDEX ix_games_aoe4world ON games (aoe4world_game_id) WHERE aoe4world_game_id IS NOT NULL;

-- What each side did in a game, in order: a whole play, or a single element
-- with the age it happened in. Both empty = not yet classified.
--   outcome         whether it worked for the side that ran it
--   preparedness    your readiness, only for what your opponent did in your games
--   response_notes  what the answering side actually did
CREATE TABLE game_plays (
  id              TEXT PRIMARY KEY,
  game_id         TEXT NOT NULL REFERENCES games (id) ON DELETE CASCADE,
  position        INTEGER NOT NULL CHECK (position >= 1),
  run_by          TEXT NOT NULL CHECK (run_by IN ('player', 'opponent')),
  strategy_id     TEXT REFERENCES strategies (id),
  element_id      TEXT REFERENCES elements (id),
  age             TEXT CHECK (age IS NULL OR age IN ('dark', 'feudal', 'castle', 'imperial')),
  outcome         TEXT CHECK (outcome IN ('worked', 'failed', 'mixed')),
  preparedness    TEXT CHECK (preparedness IN ('did_not_see', 'saw_no_plan', 'plan_misexecuted', 'handled')),
  response_id     TEXT REFERENCES responses (id) ON DELETE SET NULL,
  response_notes  TEXT,
  notes           TEXT,
  created_at      TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (NOT (strategy_id IS NOT NULL AND element_id IS NOT NULL)),
  CHECK (age IS NULL OR element_id IS NOT NULL),
  CHECK (preparedness IS NULL OR run_by = 'opponent')
);
CREATE INDEX ix_game_plays_game ON game_plays (game_id, position);
CREATE INDEX ix_game_plays_strategy ON game_plays (strategy_id) WHERE strategy_id IS NOT NULL;
CREATE INDEX ix_game_plays_element ON game_plays (element_id) WHERE element_id IS NOT NULL;

-- Footage or pages. A link of kind 'game' belongs to a game. A link of kind
-- 'guide' stands alone; civ_id and map_id say what the guide is about and
-- default the civ on its moments. Twitch broadcasts expire, so write notes
-- as if the link will die.
CREATE TABLE links (
  id                    TEXT PRIMARY KEY,
  kind                  TEXT NOT NULL DEFAULT 'game' CHECK (kind IN ('game', 'guide')),
  url                   TEXT NOT NULL,
  source                TEXT NOT NULL
                        CHECK (source IN ('youtube', 'twitch_vod', 'twitch_highlight', 'twitch_clip',
                                          'aoe4world', 'own_site', 'other')),
  title                 TEXT,
  game_id               TEXT REFERENCES games (id) ON DELETE SET NULL,
  civ_id                TEXT REFERENCES civs (id),
  map_id                TEXT REFERENCES maps (id),
  start_offset_seconds  INTEGER CHECK (start_offset_seconds IS NULL OR start_offset_seconds >= 0),
  link_status           TEXT NOT NULL DEFAULT 'live' CHECK (link_status IN ('live', 'dead')),
  last_checked_on       TEXT,
  notes                 TEXT,
  created_at            TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_links_game ON links (game_id) WHERE game_id IS NOT NULL;

-- Timestamped moments in a link.
--   In a game's link, a moment points at one of the game's plays.
--   In a guide, a moment says what it shows directly: a civ, and a play or
--   an element with an age.
--   shows: the play itself ('threat'), answering it ('response'), or both.
CREATE TABLE link_marks (
  id             TEXT PRIMARY KEY,
  link_id        TEXT NOT NULL REFERENCES links (id) ON DELETE CASCADE,
  start_seconds  INTEGER CHECK (start_seconds IS NULL OR start_seconds >= 0),
  game_play_id   TEXT REFERENCES game_plays (id) ON DELETE SET NULL,
  civ_id         TEXT REFERENCES civs (id),
  strategy_id    TEXT REFERENCES strategies (id),
  element_id     TEXT REFERENCES elements (id),
  age            TEXT CHECK (age IS NULL OR age IN ('dark', 'feudal', 'castle', 'imperial')),
  shows          TEXT CHECK (shows IS NULL OR shows IN ('threat', 'response', 'both')),
  notes          TEXT,
  created_at     TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (NOT (strategy_id IS NOT NULL AND element_id IS NOT NULL))
);
CREATE INDEX ix_link_marks_link ON link_marks (link_id);
CREATE INDEX ix_link_marks_game_play ON link_marks (game_play_id) WHERE game_play_id IS NOT NULL;
CREATE INDEX ix_link_marks_strategy ON link_marks (strategy_id) WHERE strategy_id IS NOT NULL;
CREATE INDEX ix_link_marks_element ON link_marks (element_id) WHERE element_id IS NOT NULL;


