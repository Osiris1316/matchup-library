-- Each play as readable text plus a canonical signature.
--   sequence:  "Dark Age barracks, then Tower rush in Dark Age"
--   signature: "dark_barracks>tower_rush@dark"
--              '>' = later step, '+' = same step, ids sorted within a step,
--              '@age' only when the element allows more than one age.
CREATE VIEW v_strategy_sequences AS
WITH RECURSIVE
ordered AS (
  SELECT
    se.strategy_id,
    se.step_no,
    e.id AS element_id,
    e.name
      || CASE WHEN se.age IS NOT NULL
                   AND e.age_dark + e.age_feudal + e.age_castle + e.age_imperial > 1
              THEN ' in ' || CASE se.age WHEN 'dark' THEN 'Dark Age' WHEN 'feudal' THEN 'Feudal Age'
                                         WHEN 'castle' THEN 'Castle Age' ELSE 'Imperial Age' END
              ELSE '' END AS label,
    e.id
      || CASE WHEN se.age IS NOT NULL
                   AND e.age_dark + e.age_feudal + e.age_castle + e.age_imperial > 1
              THEN '@' || se.age ELSE '' END AS token,
    ROW_NUMBER() OVER (PARTITION BY se.strategy_id ORDER BY se.step_no, e.id) AS rn
  FROM strategy_elements se
  JOIN elements e ON e.id = se.element_id
),
chain AS (
  SELECT strategy_id, rn, step_no, label AS sequence, token AS signature
  FROM ordered
  WHERE rn = 1
  UNION ALL
  SELECT
    o.strategy_id,
    o.rn,
    o.step_no,
    c.sequence  || CASE WHEN o.step_no = c.step_no THEN ' with ' ELSE ', then ' END || o.label,
    c.signature || CASE WHEN o.step_no = c.step_no THEN '+' ELSE '>' END || o.token
  FROM chain c
  JOIN ordered o ON o.strategy_id = c.strategy_id AND o.rn = c.rn + 1
)
SELECT
  s.id   AS strategy_id,
  s.name AS strategy_name,
  c.rn   AS element_count,
  c.sequence,
  c.signature
FROM strategies s
JOIN chain c ON c.strategy_id = s.id
WHERE c.rn = (SELECT MAX(o.rn) FROM ordered o WHERE o.strategy_id = s.id);

-- What each side did in each game, with the civ that did it and the civ that
-- answered it.
CREATE VIEW v_game_plays_resolved AS
SELECT
  gp.id AS game_play_id,
  gp.game_id,
  gp.position,
  gp.run_by,
  gp.strategy_id,
  gp.element_id,
  gp.age,
  gp.outcome,
  gp.preparedness,
  g.is_mine,
  g.played_on,
  g.map_id,
  m.map_type_id,
  g.result,
  CASE gp.run_by WHEN 'player' THEN g.player_civ_id ELSE g.opponent_civ_id END AS ran_civ_id,
  CASE gp.run_by WHEN 'player' THEN g.opponent_civ_id ELSE g.player_civ_id END AS answer_civ_id
FROM game_plays gp
JOIN games g ON g.id = gp.game_id
LEFT JOIN maps m ON m.id = g.map_id;

-- Every moment with what it shows and which civ did it: from the game play
-- it points at, or set on the moment itself in a guide.
CREATE VIEW v_marks_resolved AS
SELECT
  lm.id AS mark_id,
  lm.link_id,
  l.kind AS link_kind,
  l.game_id,
  lm.game_play_id,
  lm.start_seconds,
  COALESCE(lm.strategy_id, gp.strategy_id) AS strategy_id,
  COALESCE(lm.element_id, gp.element_id) AS element_id,
  COALESCE(lm.age, gp.age) AS age,
  lm.shows,
  CASE WHEN l.link_status = 'live' THEN 1 ELSE 0 END AS is_live,
  COALESCE(lm.civ_id,
           CASE gp.run_by WHEN 'player' THEN g.player_civ_id WHEN 'opponent' THEN g.opponent_civ_id END) AS civ_id,
  gp.outcome
FROM link_marks lm
JOIN links l ON l.id = lm.link_id
LEFT JOIN game_plays gp ON gp.id = lm.game_play_id
LEFT JOIN games g ON g.id = gp.game_id;

-- Health check: one row, one count per kind of problem. All zero = healthy.
CREATE VIEW v_health AS
SELECT
  (SELECT COUNT(*) FROM strategy_elements x JOIN elements e ON e.id = x.element_id
    WHERE x.age IS NOT NULL
      AND CASE x.age WHEN 'dark' THEN e.age_dark WHEN 'feudal' THEN e.age_feudal
                     WHEN 'castle' THEN e.age_castle ELSE e.age_imperial END = 0
  ) AS step_age_not_allowed,
  (SELECT COUNT(*) FROM civ_element_tags x JOIN elements e ON e.id = x.element_id
    WHERE x.age IS NOT NULL
      AND CASE x.age WHEN 'dark' THEN e.age_dark WHEN 'feudal' THEN e.age_feudal
                     WHEN 'castle' THEN e.age_castle ELSE e.age_imperial END = 0
  ) AS tag_age_not_allowed,
  (SELECT COUNT(*) FROM game_plays x JOIN elements e ON e.id = x.element_id
    WHERE x.age IS NOT NULL
      AND CASE x.age WHEN 'dark' THEN e.age_dark WHEN 'feudal' THEN e.age_feudal
                     WHEN 'castle' THEN e.age_castle ELSE e.age_imperial END = 0
  ) AS game_age_not_allowed,
  (SELECT COUNT(*) FROM link_marks x JOIN elements e ON e.id = x.element_id
    WHERE x.age IS NOT NULL
      AND CASE x.age WHEN 'dark' THEN e.age_dark WHEN 'feudal' THEN e.age_feudal
                     WHEN 'castle' THEN e.age_castle ELSE e.age_imperial END = 0
  ) AS mark_age_not_allowed,
  (SELECT COUNT(*) FROM link_marks lm
    JOIN links l ON l.id = lm.link_id
    JOIN game_plays gp ON gp.id = lm.game_play_id
    WHERE l.game_id IS NULL OR gp.game_id <> l.game_id
  ) AS marks_on_another_games_play,
  (SELECT COUNT(*) FROM game_plays gp JOIN games g ON g.id = gp.game_id
    WHERE g.is_mine = 0 AND gp.preparedness IS NOT NULL
  ) AS preparedness_outside_my_games,
  (SELECT COUNT(*) FROM game_plays x JOIN strategies s ON s.id = x.strategy_id WHERE s.merged_into_id IS NOT NULL)
  + (SELECT COUNT(*) FROM civ_element_tags x JOIN strategies s ON s.id = x.strategy_id WHERE s.merged_into_id IS NOT NULL)
  + (SELECT COUNT(*) FROM link_marks x JOIN strategies s ON s.id = x.strategy_id WHERE s.merged_into_id IS NOT NULL)
  + (SELECT COUNT(*) FROM responses x JOIN strategies s ON s.id = x.strategy_id WHERE s.merged_into_id IS NOT NULL)
  AS references_to_merged_strategies,
  (SELECT COUNT(*) FROM strategies a JOIN strategies b ON b.id = a.merged_into_id WHERE b.merged_into_id IS NOT NULL)
  AS merge_chains,
  (SELECT COUNT(*) FROM (
     SELECT vs.signature FROM v_strategy_sequences vs
     JOIN strategies s ON s.id = vs.strategy_id
     WHERE s.is_active = 1
     GROUP BY vs.signature HAVING COUNT(*) > 1)
  ) AS duplicate_strategy_groups;
